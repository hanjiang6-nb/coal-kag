_ID_OR_URL = re.compile(r"^(?:[a-z][a-z0-9+.-]*://|[0-9a-fA-F]{16,}$)")
_FORMULA = re.compile(r"^(?:[A-Z][a-z]?\d*|[()\[\]·.＋+−\-]|[₀-₉⁰-⁹])+?$")
_NUMERIC = re.compile(r"^[\d\s.,%‰+−\-–—:/<>=≤≥()\[\]]+$")
_LABELS_CASEFOLD = {key.casefold(): value for key, value in LABELS.items()}


def _key(text):
    return " ".join(text.split()).casefold()


def translate_name(text):
    """Translate a display name, retaining unknown proper names and identifiers.

    Matching does not alter source data. Known words are matched as complete
    names; conservative suffix rules translate only the descriptive component
    of an otherwise unrecognized proper name, e.g. ``Soutpansberg coals``.
    """
    if not isinstance(text, str) or not text:
        return text
    if _ID_OR_URL.match(text) or _NUMERIC.fullmatch(text):
        return text
    normalized = _key(text)
    if normalized in NAME_TRANSLATIONS:
        return NAME_TRANSLATIONS[normalized]
    # No chemical symbol or formula is a dictionary key. Their case-sensitive
    # spelling is retained, so Co and CO remain distinguishable. Known named
    # acronyms (e.g. AMD and PAHs) have already received explicit translations.
    if _FORMULA.fullmatch(text):
        return text
    # Keep sample IDs, local seam designations and the spelling of proper nouns.
    patterns = (
        (r"^(.+?)\s+coal\s*\(sample\s+([^()]+)\)$", r"\1煤（样品 \2）"),
        (r"^(.+?)\s+pyrite\s*\(sample\s+([^()]+)\)$", r"\1黄铁矿（样品 \2）"),
        (r"^bright coal seam\s*\(([^()]+)\)$", r"亮煤层（\1）"),
        (r"^dull coal seam\s*\(([^()]+)\)$", r"暗煤层（\1）"),
        (r"^first coal-sublayer\s*\(([^()]+)\)$", r"第一煤分层（\1）"),
        (r"^coal-sublayer\s+(.+)$", r"煤分层 \1"),
        (r"^coal seams\s+(.+)$", r"煤层 \1"),
        (r"^seams\s+(.+)$", r"煤层 \1"),
        (r"^seam\s+(.+)$", r"煤层 \1"),
        (r"^no\.\s*(\d+)\s+coal seam$", r"\1号煤层"),
        (r"^no\.\s*(\d+)\s+coal$", r"\1号煤层"),
        (r"^no\.\s*(\d+)\s+li-rich coal$", r"\1号富锂煤层"),
        (r"^(.+?)\s+coal source$", r"\1煤源"),
        (r"^(.+?)\s+coal seam$", r"\1煤层"),
        (r"^(.+?)\s+coal mine$", r"\1煤矿"),
        (r"^(.+?)\s+coalfields?$", r"\1煤田"),
        (r"^(.+?)\s+coals?$", r"\1煤"),
        (r"^(.+?)\s+basin$", r"\1盆地"),
        (r"^(.+?)\s+trough$", r"\1凹陷"),
        (r"^(.+?)\s+fold belt$", r"\1褶皱带"),
        (r"^(.+?)\s+deposits?$", r"\1矿床"),
        (r"^(.+?)\s+formation$", r"\1组"),
        (r"^(.+?)\s+(?:group|gp)$", r"\1群"),
        (r"^(.+?)\s+aquifers$", r"\1含水层"),
        (r"^(.+?)\s+samples$", r"\1样品"),
        (r"^(.+?)\s+mine$", r"\1矿"),
        (r"^(.+?)\s+area$", r"\1地区"),
    )
    for pattern, replacement in patterns:
        if re.fullmatch(pattern, text, flags=re.IGNORECASE):
            return re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text


def translate_term(text):
    """Translate a known field, status, predicate or controlled feature value.

    Unrecognized strings are passed to :func:`translate_name`; compound field
    names are never guessed by splitting arbitrary identifiers.
    """
    if not isinstance(text, str) or not text:
        return text
    normalized = _key(text)
    if normalized in _LABELS_CASEFOLD:
        return _LABELS_CASEFOLD[normalized]
    return translate_name(text)
