import json
from pathlib import Path
import tempfile
import unittest

from scripts.cluster_ontology_candidates import classify, similarity, cluster_profiles, feature_views, build
from scripts.validate_ontology_routing import validate


def profile(name,route,attributes,relations):
    policy=classify('synthetic material' if route=='relation' else 'coal gangue' if route=='hybrid' else 'quartz','sample or material' if route!='attribute' else 'mineral')
    return dict(name=name,policy=policy,partition=[route,'material','source_mention'],attributes=attributes,relations=relations)


class RoutingTests(unittest.TestCase):
    def test_origin_cues_are_local_and_ambiguous_samples_abstain(self):
        self.assertEqual(classify('quartz','mineral','near a synthetic material')['route'],'attribute')
        self.assertEqual(classify('synthetic quartz','mineral')['route'],'relation')
        self.assertEqual(classify('coal gangue','sample or material')['route'],'hybrid')
        self.assertEqual(classify('fly ash','sample or material','from a coal-fired power plant')['route'],'relation')
        self.assertEqual(classify('fly ash','sample or material','sample description unavailable')['route'],'pending')
        self.assertEqual(classify('samples','sample or material','a factory collected samples')['route'],'pending')
        for kind in ['geological time','geographic location','geological process','coal seam']:
            self.assertEqual(classify('object',kind)['route'],'structural_relation')

    def test_primary_views_have_different_effects_and_missingness_abstains(self):
        profiles={'a':profile('a','attribute',['x','y'],['r1','r2']),
                  'b':profile('b','attribute',['x','y'],['different','roles'])}
        self.assertAlmostEqual(similarity('a','b',profiles),0.8)
        for row in profiles.values():row.update(policy=classify('synthetic material','sample or material'),partition=['relation','material','source_mention'])
        self.assertAlmostEqual(similarity('a','b',profiles),0.2)
        profiles['b']['attributes']=['different','values'];profiles['b']['relations']=['r1','r2']
        self.assertAlmostEqual(similarity('a','b',profiles),0.8)
        groups,pending=cluster_profiles(profiles)
        self.assertEqual(len(groups),1);self.assertEqual(len(groups[0]['members']),2);self.assertFalse(pending)
        profiles['b']['relations']=[]
        self.assertIsNone(similarity('a','b',profiles))
        _,pending=cluster_profiles(profiles)
        self.assertEqual(pending[0]['entity'],'b')

    def test_hybrid_requires_both_views_and_complete_link_blocks_chains(self):
        rows={'a':profile('a','hybrid',['x','y'],[])}
        groups,pending=cluster_profiles(rows)
        self.assertFalse(groups);self.assertEqual(len(pending),1)
        rows={k:profile(k,'attribute',vals,[]) for k,vals in
              [('a',['x','y']),('b',['x','y','z']),('c',['y','z'])]}
        groups,pending=cluster_profiles(rows,0.6)
        self.assertEqual(sorted(len(g['members']) for g in groups),[1,2])
        self.assertFalse(pending)

    def test_relation_signatures_preserve_direction_not_document_or_names(self):
        nodes={key:dict(id=key,kind='entity_mention',annotation=dict(text=name,type=kind),layer='binary')
               for key,name,kind in [('a','synthetic A','sample or material'),('b','natural stone','rock')]}
        nodes['r']=dict(id='r',kind='relations',predicate='has component',default_fact_eligible=True)
        nodes['ignored']=dict(id='ignored',kind='relations',predicate='generated by',default_fact_eligible=False)
        edges=[dict(source='r',target='a',type='HEAD'),dict(source='r',target='b',type='TAIL'),
               dict(source='ignored',target='a',type='HEAD'),dict(source='ignored',target='b',type='TAIL')]
        _,_,relations,_=feature_views(nodes,edges)
        self.assertEqual(relations['a'],{json.dumps(['out','has component','rock'],ensure_ascii=False)})
        self.assertEqual(relations['b'],{json.dumps(['in','has component','sample or material'],ensure_ascii=False)})
        self.assertNotIn('synthetic A',str(relations))

    def test_build_covers_objects_and_does_not_modify_input(self):
        with tempfile.TemporaryDirectory() as tmp:
            root=Path(tmp);source=root/'source';source.mkdir()
            nodes=[dict(id='a',kind='entity_mention',annotation=dict(text='samples',type='sample or material'),layer='binary')]
            raw=json.dumps(nodes[0])+'\n'
            (source/'nodes.jsonl').write_text(raw,encoding='utf-8');(source/'edges.jsonl').write_text('',encoding='utf-8')
            result=build(source,root/'output')
            self.assertEqual(result['objects'],1);self.assertEqual(result['pending_objects'],1)
            self.assertEqual((source/'nodes.jsonl').read_text(encoding='utf-8'),raw)
            self.assertTrue((root/'output/聚类策略与结果.html').is_file())
            self.assertTrue((root/'output/属性关系聚类图谱.html').is_file())
            self.assertTrue(validate(source,root/'output')['passed'])
            profiles_path=root/'output/entity_profiles.jsonl'
            row=json.loads(profiles_path.read_text(encoding='utf-8'))
            row['relations']=['fabricated_role']
            profiles_path.write_text(json.dumps(row)+'\n',encoding='utf-8')
            with self.assertRaises(ValueError):validate(source,root/'output')
            with self.assertRaises(ValueError):build(source,root/'output')
            with self.assertRaises(ValueError):build(source,root/'bad',0)
